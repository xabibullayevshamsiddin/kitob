import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, relative, resolve } from 'node:path';

const projectRoot = resolve('..');
const output = resolve(projectRoot, 'public/offline');
const publicRoot = resolve(projectRoot, 'public');
const files = [];
async function walk(dir) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const file = join(dir, entry.name);
    if (entry.isDirectory()) await walk(file);
    else files.push(file);
  }
}
await walk(output);
const relativeAssets = files
  .filter((file) => {
    const path = relative(output, file).replaceAll('\\', '/');
    return !path.startsWith('.vite/') && !path.toLowerCase().endsWith('.woff');
  })
  .map((file) => `./${relative(publicRoot, file).replaceAll('\\', '/')}`);
for (const icon of [
  'icons/apple-touch-icon.png',
  'icons/kitobxon-192.png',
  'icons/kitobxon-512.png',
  'icons/kitobxon-192.svg',
  'icons/kitobxon-512.svg',
  'icons/kitobxon-maskable.svg',
]) relativeAssets.push(`./${icon}`);
const manifest = await readFile(join(output, '.vite/manifest.json'), 'utf8');
const version = createHash('sha256').update(manifest).update(relativeAssets.join('\n')).digest('hex').slice(0, 12);
const source = `/* Generated by offline-app/scripts/postbuild.mjs. */\nself.KITOB_PWA_VERSION = ${JSON.stringify(version)};\nself.KITOB_PWA_ASSETS = ${JSON.stringify(relativeAssets, null, 2)};\n`;
await writeFile(join(publicRoot, 'pwa-precache.js'), source, 'utf8');
console.log(`PWA precache manifest: ${relativeAssets.length} files, version ${version}`);
